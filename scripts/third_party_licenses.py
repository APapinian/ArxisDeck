"""Writes THIRD-PARTY-LICENSES.md: every crate compiled into Arxis Deck with its licence texts,
taken from vendor/ (run from the project folder: python3 scripts/third_party_licenses.py).
scripts/check.sh fails when the file is out of date."""

import hashlib
import os
import subprocess
import sys

OUT = "THIRD-PARTY-LICENSES.md"
TEXT_PREFIXES = ("LICENSE", "LICENCE", "COPYING", "UNLICENSE", "NOTICE")


def crates():
    out = subprocess.run(
        ["cargo", "tree", "-e", "normal", "--prefix", "none", "--offline", "--format", "{p}|{l}"],
        check=True, capture_output=True, text=True,
    ).stdout
    seen = {}
    for line in out.splitlines():
        p, _, lic = line.partition("|")
        parts = p.split()
        if len(parts) < 2 or parts[0] == "arxis-deck":
            continue
        name, version = parts[0], parts[1].lstrip("v")
        seen[(name, version)] = lic.replace(" (*)", "").strip()
    return sorted(seen.items())


def vendor_dir(name, version):
    for d in (f"vendor/{name}-{version}", f"vendor/{name}"):
        toml = os.path.join(d, "Cargo.toml")
        if os.path.isfile(toml) and f'version = "{version}"' in open(toml, encoding="utf-8").read():
            return d
    sys.exit(f"{name} {version} is not in vendor/")


def main():
    rows, texts, first_seen = [], [], {}
    for (name, version), lic in crates():
        d = vendor_dir(name, version)
        files = sorted(f for f in os.listdir(d) if f.upper().startswith(TEXT_PREFIXES) and os.path.isfile(os.path.join(d, f)))
        if not files:
            sys.exit(f"{name} {version} has no licence file in {d}")
        rows.append(f"| {name} | {version} | {lic} |")
        for f in files:
            body = open(os.path.join(d, f), encoding="utf-8", errors="replace").read().strip()
            digest = hashlib.sha256(body.encode()).hexdigest()
            texts.append(f"### {name} {version}: {f}\n")
            if digest in first_seen:
                texts.append(f"Same text as {first_seen[digest]}.\n")
            else:
                first_seen[digest] = f"{name} {version} ({f})"
                texts.append("```text\n" + body + "\n```\n")
    doc = [
        "# Third-party licences",
        "",
        "Arxis Deck itself is GPL-3.0-or-later (see `LICENSE`). It contains the Rust crates below,",
        "compiled into the program; their licence texts follow. Generated by",
        "`scripts/third_party_licenses.py` from `vendor/`; do not edit by hand.",
        "",
        "- **SQLite** is compiled in through `libsqlite3-sys`; SQLite itself is in the public domain.",
        "- **Qt 6** (Core, Gui, Qml, Quick; LGPL-3.0) is not included: it is linked from the system",
        "  or, in the Flatpak package, from the KDE runtime, which ships its own licence texts.",
        "",
        "| Crate | Version | Licence |",
        "|---|---|---|",
        *rows,
        "",
        "## Licence texts",
        "",
        *texts,
    ]
    content = "\n".join(doc)
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != content:
            sys.exit(f"{OUT} is out of date: run python3 scripts/third_party_licenses.py")
        return
    open(OUT, "w", encoding="utf-8").write(content)
    print(f"{OUT}: {len(rows)} crates, {len(first_seen)} distinct licence texts")


if __name__ == "__main__":
    main()
